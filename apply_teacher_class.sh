#!/usr/bin/env bash
# ==========================================================================
# Bored Academy — teacher-class.html (roster + assign lessons)
#
# Run AFTER apply_architecture.sh, apply_roles_and_locking.sh,
# apply_signup_flow.sh, and apply_dashboards.sh, from the repo root.
#   chmod +x apply_teacher_class.sh
#   ./apply_teacher_class.sh
#
# What it does:
#   1. Generates assets/js/data/lesson-index.js — a lightweight
#      {courseId: [{id,title,unit}]} index built from the three course
#      data files, so the "assign a lesson" picker doesn't need to load
#      full lesson content (quiz/html/vocab) just to list lesson titles.
#   2. Patches course-loader.js so a lesson's lock state actually reflects
#      real BoredAssignments entries: assignedTo is now populated from
#      BoredAssignments.forClass() for the signed-in student's classes,
#      filtered to unlocked (unlockDate has passed) assignments — not just
#      a hardcoded "first 2 lessons free" rule.
#   3. Replaces the teacher/teacher-class.html stub with a working page:
#      roster (list of students in the class), an "assign a lesson" form
#      (course -> lesson -> unlock/due date -> points), and a list of
#      current assignments for the class.
#
# Safe to re-run — regenerates lesson-index.js each time (cheap + always
# current), and checks for markers before re-patching course-loader.js.
# ==========================================================================
set -euo pipefail

log() { printf '\033[1;36m▸ %s\033[0m\n' "$1"; }
skip() { printf '  (skip) %s\n' "$1"; }

DATA_DIR="assets/js/data"
LOADER="assets/js/courses/course-loader.js"

[ -f "$LOADER" ] || { echo "Run apply_architecture.sh + apply_roles_and_locking.sh first." >&2; exit 1; }

# --------------------------------------------------------------------------
# 1. Generate lesson-index.js
# --------------------------------------------------------------------------
log "Generating $DATA_DIR/lesson-index.js"
python3 - "$DATA_DIR" <<'PYEOF'
import sys, re, json, os

data_dir = sys.argv[1]
courses = {
    'chemistry': 'chemistry-data.js',
    'ielts': 'ielts-data.js',
    'cet4': 'cet4-data.js',
}

index = {}
for course_id, fname in courses.items():
    path = os.path.join(data_dir, fname)
    if not os.path.exists(path):
        print(f"  WARNING: {path} not found, skipping {course_id}", file=sys.stderr)
        continue
    src = open(path).read()
    lessons = []
    for m in re.finditer(
        r'unit\s*:\s*"((?:[^"\\]|\\.)*)"\s*,\s*id\s*:\s*"((?:[^"\\]|\\.)*)"\s*,\s*title\s*:\s*"((?:[^"\\]|\\.)*)"',
        src
    ):
        unit, lid, title = m.groups()
        lessons.append({"id": lid, "title": title, "unit": unit})
    index[course_id] = lessons
    print(f"  {course_id}: {len(lessons)} lessons")

out_path = os.path.join(data_dir, 'lesson-index.js')
with open(out_path, 'w') as f:
    f.write("/* AUTO-GENERATED by apply_teacher_class.sh — do not hand-edit.\n")
    f.write("   Regenerate by re-running that script after editing course data files. */\n")
    f.write("window.LESSON_INDEX = " + json.dumps(index, indent=2, ensure_ascii=False) + ";\n")
print(f"  wrote {out_path}")
PYEOF

# --------------------------------------------------------------------------
# 2. Patch course-loader.js: real assignment-based unlocking
# --------------------------------------------------------------------------
if grep -q 'BOREDACADEMY_ASSIGNMENT_UNLOCK_PATCH' "$LOADER"; then
  skip "$LOADER already patched for assignment-based unlocking"
else
  log "Patching $LOADER (assignment-based unlocking)"
  python3 - "$LOADER" <<'PYEOF'
import sys
path = sys.argv[1]
src = open(path).read()

old = '''// BOREDACADEMY_LOCK_PATCH
// First 2 lessons of each unit are free demo lessons (matches the "Guest
// can complete first 2-3 lessons of every course" rule). Everything else
// needs BoredPermissions.canAccessLesson() to return true.
(function markFreeLessons(){
  const seen = {};
  DATA.forEach(l => {
    seen[l.unit] = seen[l.unit] || 0;
    l.free = seen[l.unit] < 2;
    seen[l.unit]++;
  });
})();'''

new = '''// BOREDACADEMY_LOCK_PATCH
// BOREDACADEMY_ASSIGNMENT_UNLOCK_PATCH
// First 2 lessons of each unit are free demo lessons (matches the "Guest
// can complete first 2-3 lessons of every course" rule). Everything else
// needs BoredPermissions.canAccessLesson() to return true, which checks
// lesson.assignedTo against the user's classIds — populated below from
// real BoredAssignments entries for classes the signed-in user is in.
(function markFreeLessons(){
  const seen = {};
  DATA.forEach(l => {
    seen[l.unit] = seen[l.unit] || 0;
    l.free = seen[l.unit] < 2;
    seen[l.unit]++;
  });
})();

(function applyAssignments(){
  if(!window.BoredAssignments) return;
  const user = window.BoredAuth ? window.BoredAuth.currentUser() : null;
  const classIds = (user && user.classIds) || [];
  if(!classIds.length) return;

  const now = Date.now();
  DATA.forEach(l => { l.assignedTo = l.assignedTo || []; });

  classIds.forEach(function(classId){
    BoredAssignments.forClass(classId).forEach(function(a){
      if(a.courseId !== COURSE_ID) return;
      if(!BoredAssignments.isUnlocked(a, now)) return; // not open yet
      const lesson = DATA.find(function(l){ return l.id === a.lessonId; });
      if(lesson && lesson.assignedTo.indexOf(classId) === -1){
        lesson.assignedTo.push(classId);
      }
    });
  });
})();'''

if old not in src:
    print("WARNING: could not find markFreeLessons block, aborting.", file=sys.stderr)
    sys.exit(1)
src = src.replace(old, new)
open(path, 'w').write(src)
print("  patched applyAssignments()")
PYEOF
fi

# --------------------------------------------------------------------------
# 3. Ensure course pages load classroom/assignments.js (needed by the patch)
# --------------------------------------------------------------------------
log "Ensuring courses/*.html load assignments.js"
for f in courses/*.html; do
  [ -f "$f" ] || continue
  if grep -q 'classroom/assignments.js' "$f"; then
    skip "$f already wired"
    continue
  fi
  python3 - "$f" <<'PYEOF'
import sys
path = sys.argv[1]
src = open(path).read()
needle = '<script src="../assets/js/courses/course-loader.js">'
inject = '<script src="../assets/js/classroom/assignments.js"></script>\n'
if needle in src and inject not in src:
    src = src.replace(needle, inject + needle, 1)
    open(path, 'w').write(src)
    print("  wired:", path)
PYEOF
done

# --------------------------------------------------------------------------
# 3b. Fix an id-collision bug: classroom.js and assignments.js generate ids
#     from Date.now().toString(36) alone, so two classes/assignments created
#     within the same millisecond overwrite each other in localStorage.
#     Found this while testing the assign-a-lesson flow end to end — a
#     teacher assigning two lessons back-to-back would silently lose the
#     first assignment. Add a random suffix so ids are always unique.
# --------------------------------------------------------------------------
log "Fixing id-collision bug in classroom.js / assignments.js"

fix_id_collision() {
  local file="$1" prefix="$2"
  [ -f "$file" ] || return 0
  if ! grep -q "const id = '${prefix}_' + Date.now().toString(36);" "$file"; then
    skip "$file already fixed (or id line not in expected form)"
    return 0
  fi
  python3 - "$file" "$prefix" <<'PYEOF'
import sys
path, prefix = sys.argv[1], sys.argv[2]
src = open(path).read()
old = "const id = '" + prefix + "_' + Date.now().toString(36);"
new = ("// Random suffix avoids id collisions when two records are created\n"
       "    // within the same millisecond (Date.now() alone is not unique enough).\n"
       "    const id = '" + prefix + "_' + Date.now().toString(36) + '_' + Math.random().toString(36).slice(2, 8);")
if old in src:
    src = src.replace(old, new, 1)
    open(path, 'w').write(src)
    print("  fixed:", path)
else:
    print("  WARNING: expected id-generation line not found in", path, "— check manually.", file=sys.stderr)
PYEOF
}

fix_id_collision "assets/js/classroom/classroom.js"   "c"
fix_id_collision "assets/js/classroom/assignments.js" "a"

# --------------------------------------------------------------------------
# 4. Build teacher/teacher-class.html
# --------------------------------------------------------------------------
log "Writing teacher/teacher-class.html"
if [ -f "teacher/teacher-class.html" ]; then
  cp "teacher/teacher-class.html" "teacher/teacher-class.html.bak"
  echo "  backed up existing file to teacher/teacher-class.html.bak"
fi

